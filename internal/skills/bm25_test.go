func TestBM25UsesStatisticsBodyAndCJK(t *testing.T) {
	r := &Registry{}
	r.Replace([]Skill{{Name: "reader", Description: "extract text", Body: "process pdf documents and 发票票据"}, {Name: "other", Description: "handle network", Body: "http requests"}})
	for _, query := range []string{"pdf", "发票"} {
		hits := r.Search(query, 5)
		if len(hits) != 1 || hits[0].Skill.Name != "reader" || hits[0].Score <= 0 {
			t.Fatalf("%s: %+v", query, hits)
		}
	}
	if len(r.Search("unknown", 5)) != 0 || len(r.Search("", 5)) != 0 {
		t.Fatal("zero-match padding")
	}
	if got := strings.Join(Tokenize("PDF 发票 x 1 HTTP2"), "|"); got != "pdf|发|票|http2" {
		t.Fatal(got)
	}
	// A single document contains name twice, description once and body once.
	s := buildSnapshot([]Skill{{Name: "pdf", Description: "pdf", Body: "pdf"}})
	hits := search(s, "pdf", 1)
	want := math.Log1p(.5/1.5) * 4 * 2.5 / (4 + 1.5)
	if len(hits) != 1 || math.Abs(hits[0].Score-want) > 1e-12 {
		t.Fatal(hits, want)
	}
}

func TestBM25MatchesReferenceNumericalVectors(t *testing.T) {
	// Generated by executing the readable reference BM25Okapi on the exact same
	// name/name/description/body documents; no model or external service involved.
	r := &Registry{}
	r.Replace([]Skill{
		{Name: "pdf", Description: "extract invoices", Body: "pdf parse 发票"},
		{Name: "tests", Description: "run checks", Body: "go test assertion"},
		{Name: "weather", Description: "forecast rain", Body: "阳光"},
	})
	for _, v := range []struct {
		query, name string
		score       float64
	}{
		{"pdf 发票", "pdf", 3.421514990448991},
		{"go test", "tests", 1.9616585060234528},
		{"雨 forecast", "weather", 1.0482144688674937},
	} {
		h := r.Search(v.query, 5)
		if len(h) != 1 || h[0].Skill.Name != v.name || math.Abs(h[0].Score-v.score) > 1e-12 {
			t.Fatalf("query=%q got=%+v want=%g", v.query, h, v.score)
		}
	}
	if len(r.Search("unknown", 5)) != 0 {
		t.Fatal("unknown query should be empty")
	}
}

func TestAlwaysAndActivatedReferenceLimits(t *testing.T) {
	list := []Skill{}
	for i := range 7 {
		list = append(list, Skill{Name: strings.Repeat("a", i+1), Body: "ALWAYS_BODY", Always: true})
	}
	for _, name := range []string{"pdf-one", "pdf-two", "pdf-three", "pdf-four", "pdf-five", "pdf-six"} {
		list = append(list, Skill{Name: name, Description: "pdf document extraction", Path: "/registered/" + name + "/SKILL.md", Body: "ROUTED_BODY"})
	}
	r := &Registry{}
	r.Replace(list)
	s := r.Resolve("pdf")
	if len(s.Metadata.AlwaysIDs) != 5 || len(s.Metadata.CandidateIDs) != 5 || len(s.Metadata.InjectedIDs) != 2 || len(s.Metadata.ReferencedIDs) != 3 {
		t.Fatalf("%+v", s.Metadata)
	}
	if strings.Count(s.ActiveText, "ALWAYS_BODY") != 5 || strings.Count(s.SelectedText, "ROUTED_BODY") != 2 || strings.Contains(s.SelectedText, "ALWAYS_BODY") {
		t.Fatal("duplicate/missing body")
	}
	if !strings.Contains(s.SelectedText, "skill_read") {
		t.Fatal("no read-back route")
	}
	empty := r.Resolve("")
	if empty.SelectedText != "" || empty.ActiveText == "" {
		t.Fatal("always tied to query")
	}
	// Ambiguous body-only lexical hits are references, not silently activated.
	r.Replace([]Skill{{Name: "reader", Description: "parse documents", Path: "/registered/reader/SKILL.md", Body: "pdf extraction"}})
	s = r.Resolve("pdf extraction")
	if len(s.Metadata.InjectedIDs) != 0 || len(s.Metadata.ReferencedIDs) != 1 {
		t.Fatal(s.Metadata)
	}
	blocked := r.ResolveWithReferences("pdf extraction", false)
	if blocked.SelectedText != "" || len(blocked.Metadata.ReferencedIDs) != 0 || len(blocked.Metadata.UnavailableReferences) != 1 {
		t.Fatal("unreadable reference shown", blocked)
	}
}

func TestIndexNameWeightAndBodyCharacterLimit(t *testing.T) {
	r := &Registry{}
	r.Replace([]Skill{{Name: "pdf", Body: "generic"}, {Name: "other", Body: "pdf"}})
	h := r.Search("pdf", 5)
	if len(h) != 2 || h[0].Skill.Name != "pdf" {
		t.Fatal(h)
	}
	r.Replace([]Skill{{Name: "reader", Body: strings.Repeat("甲", 4000) + " hiddenneedle"}})
	if len(r.Search("hiddenneedle", 5)) != 0 {
		t.Fatal("body index exceeded 4000 characters")
	}
	// Rendering keeps complete selected instructions; it is no longer byte-sliced.
	r.Replace([]Skill{{Name: "reader", Path: "/registered/reader/SKILL.md", Body: strings.Repeat("complete instruction\n", 1000)}})
	if !strings.Contains(r.Render("reader"), strings.TrimSpace(strings.Repeat("complete instruction\n", 1000))) {
		t.Fatal("skill body clipped")
	}
}

func TestSnapshotSwapConcurrentReaders(t *testing.T) {
	r := &Registry{}
	r.Replace([]Skill{{Name: "alpha", Description: "marker", Body: "OLD"}})
	var wg sync.WaitGroup
	for range 8 {
		wg.Go(func() {
			for range 100 {
				h := r.Search("marker", 5)
				if len(h) != 1 || (h[0].Skill.Name == "alpha" && h[0].Skill.Body != "OLD") || (h[0].Skill.Name == "beta" && h[0].Skill.Body != "NEW") {
					t.Error("mixed snapshot", h)
				}
			}
		})
	}
	for i := range 100 {
		if i%2 == 0 {
			r.Replace([]Skill{{Name: "beta", Description: "marker", Body: "NEW"}})
		} else {
			r.Replace([]Skill{{Name: "alpha", Description: "marker", Body: "OLD"}})
		}
	}
	wg.Wait()
}
